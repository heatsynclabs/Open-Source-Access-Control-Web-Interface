#!/usr/bin/env python3
"""Write app/models/arizona_map.rb: Arizona's state and county outlines as SVG
path data, for the analytics map of where members live.

Usage:
    python3 -I script/arizona_map.py <counties-10m.json> app/models/arizona_map.rb

The source is us-atlas 3.0.1's counties-10m.json (TopoJSON of the US Census
Bureau's cartographic boundary files, public domain;
https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/counties-10m.json). Run once;
the site never fetches it. Two views share one projection (longitude scaled
by cos 34 degrees): the whole state, and the Phoenix metro (METRO below).
Paths are simplified to half a pixel.
"""
import json
import math
import sys

STATE_ID = "04"
COS = math.cos(math.radians(34))
VIEWS = {  # name: (west, east, south, north, pixels per degree of latitude)
    "state": (-114.85, -109.0, 31.3, 37.03, 92.0),
    "metro": (-112.45, -111.45, 33.05, 33.75, 560.0),
}


def arcs_of(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    out = []
    for arc in topo["arcs"]:
        x = y = 0
        points = []
        for dx, dy in arc:
            x += dx
            y += dy
            points.append((x * sx + tx, y * sy + ty))
        out.append(points)
    return out


def ring(arcs, indexes):
    points = []
    for i in indexes:
        arc = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
        points.extend(arc if not points else arc[1:])
    return points


def polygons(arcs, geometry):
    shapes = geometry["arcs"] if geometry["type"] == "MultiPolygon" else [geometry["arcs"]]
    return [[ring(arcs, r) for r in shape] for shape in shapes]


def simplify(points, tolerance):
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    length = math.hypot(x2 - x1, y2 - y1)
    far, index = 0, 0
    for i, (x, y) in enumerate(points[1:-1], 1):
        # distance to the line through the ends, or to the end itself when a ring closes
        d = abs((x2 - x1) * (y1 - y) - (x1 - x) * (y2 - y1)) / length if length else math.hypot(x - x1, y - y1)
        if d > far:
            far, index = d, i
    if far <= tolerance:
        return [points[0], points[-1]]
    return simplify(points[:index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)


def path(shapes, view):
    west, east, south, north, k = VIEWS[view]
    out = []
    for shape in shapes:
        for r in shape:
            pts = [((lon - west) * COS * k, (north - lat) * k) for lon, lat in r]
            pts = simplify(pts, 0.5)
            out.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z")
    return "".join(out)


def main(src, dest):
    topo = json.load(open(src))
    arcs = arcs_of(topo)
    state = next(g for g in topo["objects"]["states"]["geometries"] if g["id"] == STATE_ID)
    counties = sorted((g for g in topo["objects"]["counties"]["geometries"] if g["id"].startswith(STATE_ID)),
                      key=lambda g: g["properties"]["name"])
    lines = ["# Generated by script/arizona_map.py from us-atlas 3.0.1 (US Census Bureau",
             "# cartographic boundaries, public domain). Do not edit by hand.",
             "# Arizona's outline and counties as SVG path data in two views of one",
             "# projection (x = (lon - west) * cos 34 deg * k, y = (north - lat) * k).",
             "module ArizonaMap",
             "  VIEWS = {"]
    for name, (west, east, south, north, k) in VIEWS.items():
        width, height = (east - west) * COS * k, (north - south) * k
        lines.append(f'    "{name}" => {{ west: {west}, east: {east}, south: {south}, north: {north}, k: {k}, '
                     f'width: {width:.0f}, height: {height:.0f} }},')
    lines += ["  }.freeze", f"  COS = {COS!r}", "", "  STATE = {"]
    for view in VIEWS:
        lines.append(f'    "{view}" => "{path(polygons(arcs, state), view)}",')
    lines += ["  }.freeze", "", "  COUNTIES = {"]
    for view in VIEWS:
        lines.append(f'    "{view}" => {{')
        for g in counties:
            lines.append(f'      "{g["properties"]["name"]}" => "{path(polygons(arcs, g), view)}",')
        lines.append("    }.freeze,")
    lines += ["  }.freeze", "", "  module_function", "",
              "  # [x, y] of a place in a view.",
              "  def point(view, lat, lon)",
              "    v = VIEWS.fetch(view)",
              "    [((lon - v[:west]) * COS * v[:k]).round(1), ((v[:north] - lat) * v[:k]).round(1)]",
              "  end", "end", ""]
    open(dest, "w").write("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
